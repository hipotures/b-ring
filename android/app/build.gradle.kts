plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
}

// The Cargo workspace this Gradle project lives in.
val repoRoot: File = rootDir.parentFile

android {
    namespace = "io.github.hipotures.bring"
    // Current AndroidX/OkHttp releases require compiling against API 37.1+;
    // runtime behaviour is still targetSdk 36.
    compileSdk {
        version = release(37) { minorApiLevel = 2 }
    }

    // Same NDK as build-rust.sh; AGP uses it to strip the .so.
    ndkVersion = "30.0.16248370"

    defaultConfig {
        applicationId = "io.github.hipotures.bring"
        // MANAGE_EXTERNAL_STORAGE exists from API 30.
        minSdk = 30
        targetSdk = 36
        versionCode = 1
        versionName = "0.1.0"

        // Target devices (phone, Meta Quest 3) are all arm64-v8a.
        ndk { abiFilters += "arm64-v8a" }
    }

    buildFeatures { compose = true }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    // Generated by build-rust.sh (UniFFI Kotlin bindings).
    sourceSets.getByName("main").kotlin.directories.add("src/generated/kotlin")

    testOptions { unitTests.isReturnDefaultValues = true }
}

// `libbring_uniffi.so` (arm64-v8a) and its Kotlin bindings, via cargo-ndk.
val sdkPath: String = androidComponents.sdkComponents.sdkDirectory.get().asFile.path
val cargoAndroid = tasks.register<Exec>("cargoAndroid") {
    description = "Builds the Rust sync engine for arm64-v8a and generates Kotlin bindings."
    workingDir = repoRoot
    commandLine(rootDir.resolve("build-rust.sh").path)
    environment("ANDROID_HOME", sdkPath)
}

// The same library for the host, so JVM unit tests call the real engine.
val cargoHost = tasks.register<Exec>("cargoHost") {
    description = "Builds libbring_uniffi.so for the host (JVM unit tests)."
    workingDir = repoRoot
    commandLine("cargo", "build", "--locked", "-p", "bring-uniffi")
}

tasks.named("preBuild") { dependsOn(cargoAndroid) }

tasks.withType<Test>().configureEach {
    dependsOn(cargoHost)
    systemProperty("jna.library.path", repoRoot.resolve("target/debug").path)
}

dependencies {
    implementation(platform(libs.compose.bom))
    implementation(libs.compose.ui)
    implementation(libs.compose.foundation)
    implementation(libs.compose.material3)
    implementation(libs.compose.icons)
    implementation(libs.activity.compose)
    implementation(libs.core.ktx)
    implementation(libs.lifecycle.runtime.compose)
    implementation(libs.lifecycle.viewmodel.compose)
    implementation(libs.coroutines.android)
    implementation(libs.work.runtime)
    implementation(libs.media3.exoplayer)
    implementation(libs.media3.ui)
    implementation(libs.media3.okhttp)
    implementation(libs.okhttp)
    implementation(libs.coil.compose)
    implementation(libs.zxing.embedded)
    // UniFFI bindings call into the .so through JNA; the AAR carries the
    // Android jnidispatch.
    implementation("${libs.jna.get()}@aar")

    testImplementation(libs.junit)
    // Desktop JNA (with the host jnidispatch) for the native unit test.
    testImplementation(libs.jna)
}
